def phrasing_question(text: str, index: int, as_of: str) -> tuple[str, list[str]]:
    """Rewrite one question with PHRASINGS and bare months; returns (text, rule names)."""
    used = []
    for n, (name, pattern, forms) in enumerate(PHRASINGS):
        new = re.sub(pattern, forms[(index + n) % len(forms)], text)
        if new != text:
            used.append(name)
            text = new
    # Month without year (rulebook: this year unless after today, else last year), and
    # "năm ngoái" for last year's month; only for a single month mention.
    year, month = int(as_of[:4]), int(as_of[5:7])
    months = list(re.finditer(r"(?i)\btháng (\d{1,2})(?:/| năm )(\d{4})\b", text))
    # Only a question with this one date: "tháng 11, 12/2025" must keep its year.
    if len(months) == 1 and len(re.findall(r"\d/\d|\d{4}", text)) == 1:
        m = months[0]
        value, y = int(m[1]), int(m[2])
        if y == year and value <= month and index % 2:
            text, name = text[: m.start()] + f"tháng {value}" + text[m.end() :], "month_no_year"
            used.append(name)
        elif y == year - 1:
            # A bare month after today is last year's too.
            bare = value > month and index % 2
            form = f"tháng {value}" if bare else f"tháng {value} năm ngoái"
            text = text[: m.start()] + form + text[m.end() :]
            used.append("month_last_year")
    return text, used


def variants(questions: list[dict]) -> dict[str, list[dict]]:
    """Chat and phrasing variants; a question the rules leave unchanged is not repeated."""
    chat, phrasing = [], []
    for i, q in enumerate(questions):
        text = chat_question(q["question"], i)
        if text != q["question"]:
            chat.append(q | {"question": text})
        text, used = phrasing_question(q["question"], i, q["as_of_date"])
        if used:
            phrasing.append(q | {"question": text})
    return {"chat_questions": chat, "phrasing_questions": phrasing}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--questions", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="compare with src/semantics")
    args = parser.parse_args(argv)
    lines = args.questions.read_text(encoding="utf-8").splitlines()
    questions = [json.loads(line) for line in lines if line.strip()]
    splits = {"train_questions": questions, **variants(questions)}
    words, pairs = set(), set()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, rows in splits.items():
        with (args.out_dir / f"{name}.jsonl").open("w", encoding="utf-8") as out:
            for q in rows:
                out.write(json.dumps(q, ensure_ascii=False) + "\n")
                words.update(question_tokens(q["question"]))
                tokens = plain_tokens(q["question"])
                pairs.update(f"{a} {b}" for a, b in zip(tokens, tokens[1:], strict=False))
        print(f"{name}: {len(rows)} questions")
    built = {
        WORDS_FILE.name: "\n".join(sorted(words)) + "\n",
        BIGRAMS_FILE.name: "\n".join(sorted(pairs)) + "\n",
    }
    for name, text in built.items():
        (args.out_dir / name).write_text(text, encoding="utf-8")
    print(f"{len(words)} words, {len(pairs)} pairs -> {args.out_dir}")
    if args.check:
        same = all(
            (args.out_dir / name).read_bytes() == packaged.read_bytes()
            for name, packaged in [(WORDS_FILE.name, WORDS_FILE), (BIGRAMS_FILE.name, BIGRAMS_FILE)]
        )
        print("check:", "identical to src/semantics" if same else "DIFFERENT from src/semantics")
        return 0 if same else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
