    (
        "last_n_days_today",
        r"(\d+) ngày gần nhất",
        [
            r"\1 ngày qua tính cả hôm nay",
            r"\1 ngày qua (kể cả hôm nay)",
            r"\1 ngày gần đây kể cả hôm nay",
        ],
    ),
    ("shop_owner", r"của cửa hàng", ["của quán", "của tiệm", "của shop"]),
