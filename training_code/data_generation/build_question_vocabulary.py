"""Rebuild the question vocabulary read by the rule operators.

Inputs: the competition train questions (``training_code/data/train_questions.jsonl``).
Two deterministic wording variants of them are generated by fixed rules (no model, no
randomness): chat spellings (``CHAT_FORMS``) and other everyday wordings (``PHRASINGS``),
each rotated by the question's line index. The vocabulary is every casefolded word and
every adjacent accentless word pair of the train questions and of both variants.

    cd /code && PYTHONPATH=/code python3 training_code/data_generation/build_question_vocabulary.py \
        --questions training_code/data/train_questions.jsonl --out-dir /tmp/vocabulary --check

``--check`` compares the rebuilt files with ``src/semantics/question_words.txt`` and
``src/semantics/question_bigrams.txt`` byte for byte.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from src.semantics.typos import BIGRAMS_FILE, plain_tokens
from src.semantics.vocabulary import WORDS_FILE, question_tokens

# Standard wording -> chat/regional spellings (everyday Vietnamese, not from test questions).
CHAT_FORMS = [
    ("đơn hàng", ["đh"]),
    ("bao nhiêu", ["bnhiu", "nhiêu", "bn"]),
    ("hôm nay", ["hnay"]),
    ("hôm qua", ["hqua"]),
    ("tháng này", ["tháng ni"]),
    ("được", ["đc"]),
    ("không", ["ko", "hông"]),
    ("nào", ["mô"]),
    ("nhất", ["nhứt"]),
    ("còn", ["kòn"]),
    ("giùm", ["jùm"]),
    ("với", ["dới"]),
    ("vậy", ["z", "dậy"]),
    ("doanh thu", ["dthu"]),
    ("nhiều", ["nhìu"]),
    ("trước", ["trc"]),
    ("gì", ["j"]),
]


def chat_question(text: str, index: int) -> str:
    """Rewrite function words of one question with fixed chat spellings."""
    for n, (word, forms) in enumerate(CHAT_FORMS):
        pattern = re.compile(r"(?<!\w)" + re.escape(word) + r"(?!\w)", re.I)
        text = pattern.sub(forms[(index + n) % len(forms)].replace("\\", r"\\"), text)
    return re.sub(r"(?<!\w)[Tt]háng (\d{1,2})(?!\d)", r"th\1", text) if index % 2 else text


# Same meaning, other everyday wording (rulebook terms; not copied from test questions).
# Each entry: name, pattern, replacement forms (rotated by question index).
